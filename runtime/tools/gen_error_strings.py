#!/usr/bin/env python3
"""Generates error_strings.inc (cudaError_t value, name, description) from the CUDA toolkit's public driver_types.h"""
import re, sys

header = open(sys.argv[1]).read()
body = header[header.index('enum __device_builtin__ cudaError'):]
body = body[:body.index('};')]
entries = []
# each enumerator is preceded by a doc comment
for m in re.finditer(r'/\*\*((?:(?!\*/).)*)\*/\s*(cuda\w+)\s*=\s*(\d+)', body, re.S):
    doc = ' '.join(l.strip().lstrip('*').strip() for l in m.group(1).splitlines())
    doc = re.sub(r'\s+', ' ', doc).strip()
    doc = re.sub(r'\\ref\s+::?', '', doc).replace('::', '')
    first = re.split(r'(?<=[.])\s', doc)[0] if doc else m.group(2)
    entries.append((int(m.group(3)), m.group(2), first.replace('\\', '\\\\').replace('"', '\\"')))
with open(sys.argv[2], 'w') as f:
    f.write('// generated by gen_error_strings.py from the CUDA toolkit\'s public driver_types.h\n')
    for v, name, desc in entries:
        f.write(f'{{{v}, "{name}", "{desc}"}},\n')
print(len(entries), 'entries')
