# Embeds output/printf_<arch>.cubin in a C++ header (usage: generate_header.py <header> <cubin dir>)
import sys, os
out = sys.argv[1]; srcdir = sys.argv[2]
with open(out, 'w') as h:
    h.write("// generated by driverapi/kernels/printf/compile_printf.sh from printf.cu\n#pragma once\n\n#include <cstdint>\n\n")
    for arch in ["sm_75", "sm_80", "sm_86", "sm_87", "sm_89", "sm_90", "sm_120"]:
        data = open(os.path.join(srcdir, f"printf_{arch}.cubin"), 'rb').read()
        h.write(f"const uint8_t PRINTF_{arch.upper()}[] = {{\n")
        for i in range(0, len(data), 32):
            h.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 32]) + ",\n")
        h.write("};\n\n")
