DIMENSIONS = 20000


def main():
    rows = []
    with open(sys.argv[1]) as f:
        next(f)
        for line in f:
            fields = [int(v) for v in line.split()]
            d, s, a, m = fields[0], fields[1], fields[2], fields[3:]
            assert len(m) == s and d == len(rows) + 2
            rows.append((s, a, m))
            if d == DIMENSIONS:
                break
    bits, nbits = 0, 0
    for s, a, m in rows:
        assert s < 32 and a < (1 << max(s - 1, 0))
        fields = [(s, 5), (a, s - 1)] + [(m[i], i + 1) for i in range(s)]
        for value, width in fields:
            assert value < (1 << width) or width == 0
            bits |= value << nbits
            nbits += width
    words = [(bits >> (32 * i)) & 0xffffffff for i in range((nbits + 31) // 32)]
    out = sys.stdout
    out.write("// Generated by blas/gen_sobol.py from new-joe-kuo-6.21201 (S. Joe and F. Y. Kuo); do not edit.\n//\n")
    out.write("".join("// " + l if l else "//" for l in (l + "\n" for l in LICENCE.split("\n"))).replace("// \n", "//\n"))
    out.write(f"\nconstexpr int SOBOL_DIMENSIONS = {DIMENSIONS};\n")
    out.write(f"constexpr unsigned int SOBOL_PACKED[{len(words)}] = {{\n")
    for i in range(0, len(words), 8):
        out.write("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",\n")
    out.write("};\n")


main()
